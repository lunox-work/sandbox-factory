/**
 * The sandbox build adapter: from a version's private provenance and the
 * slice it was cut from, a standalone project, its hidden tests and a
 * baseline check in a fresh evaluation job.
 *
 * Everything the output binds to arrives as run parameters and is checked
 * against the version record and the slice artifacts before a byte is
 * generated: a draft that changed after the run was queued fails rather
 * than building a candidate for the wrong transform. Source bytes are read
 * at the pinned commit and verified against the slice manifest's hashes.
 * Aliases are applied with the inverse proof, the project is generated by
 * the pure generator in `packages/core`, and the baseline runs the public
 * commands plus every hidden test in a job the provider creates and
 * destroys. Logs stay fixed lines; the job's output is not stored.
 */

